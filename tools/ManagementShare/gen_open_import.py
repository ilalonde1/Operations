"""Generate migration 373 (open proposals -> Submitted CRM pursuits) and its dry-run twin from the review CSV Ian approved.

Input is open_proposals.py's review CSV exactly as approved on 2026-10-20 ("Approve"); rows whose owner is unknown ("? ...")
are left out (Ian gave no owner). Per row:
  - "update #<id>": the live pursuit moves to Submitted (Stage 3); its fee is filled only if it had none; a stage-history row
    is written at the date the fee was sent, so the roll-ups' 14-day follow-up and 45-day chase count from the real date. The
    pursuit's prior stage and fee are kept in opportunities.CrmOpenProposalImport for reversal. Skipped if the pursuit is no
    longer live (stage 1) or was already imported.
  - "new": a Submitted pursuit with the owner, fee, project and client; ExternalSource 'M.OpenProposals', key 'M:<record ids>'
    (idempotent through UX_CrmEngagements_ExternalKey, migration 267), plus its stage-history row at the sent date.
Org: companies.csv id, else EXACT DisplayName with one non-retired match (the 368 rule); never LIKE; never creates orgs.
Usage: python -I gen_open_import.py <review.csv> <out migration .sql> <out dryrun .sql>"""
import csv, os, sys
review, out_sql, out_dry = sys.argv[1], sys.argv[2], sys.argv[3]
repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
comp = {}
for r in csv.DictReader(open(os.path.join(repo, 'tools', 'BdTrackingImport', 'companies.csv'), encoding='utf-8-sig')):
    if r.get('canonicalOrgId', '').strip().isdigit(): comp[r['sheetName'].strip().lower()] = int(r['canonicalOrgId'])
BY = 'migration 373 (open proposals on M:, approved by Ian 2026-10-20)'


def q(s, n=None):
    s = (s or '').replace('\r', ' ').replace('\n', ' ').strip()
    if n: s = s[:n]
    return "N'" + s.replace("'", "''") + "'"


rows, skipped = [], []
for r in csv.DictReader(open(review, encoding='utf-8-sig')):
    if r['owner'].startswith('?'): skipped.append(r['client']); continue
    key = 'M:' + r['records'].replace(' ', ',')
    eid = r['action'].split('#')[1] if r['action'].startswith('update') else 'NULL'
    notes = ' | '.join(x for x in [f"Open proposal on M: sent {r['sent']}", r['project'], f"fee in {r['currency']}" if r['fee'] else '',
                                   f"records {r['records']}"] if x)
    hint = comp.get(r['client'].strip().lower())
    rows.append('(' + ', '.join([q(key, 400), q('update' if eid != 'NULL' else 'new'), eid, q(r['owner'], 300), r['fee'] or 'NULL',
                                f"'{r['sent']}'", q(r['client'], 300), str(hint) if hint else 'NULL', q(r['project'], 1000), q(notes, 3800)]) + ')')

load = ["SET QUOTED_IDENTIFIER ON;", "SET ANSI_NULLS ON;", "SET NOCOUNT ON;", "",
        "IF OBJECT_ID('tempdb..#m') IS NOT NULL DROP TABLE #m;",
        "CREATE TABLE #m (SourceKey NVARCHAR(400) NOT NULL PRIMARY KEY, Action NVARCHAR(10) NOT NULL, EngagementId BIGINT NULL,",
        "  Owner NVARCHAR(300) NOT NULL, Fee DECIMAL(18,2) NULL, SentOn DATE NOT NULL, Client NVARCHAR(300) NOT NULL, OrgHint BIGINT NULL,",
        "  Project NVARCHAR(1000) NOT NULL, Notes NVARCHAR(MAX) NOT NULL, OrgId BIGINT NULL);",
        "INSERT INTO #m (SourceKey, Action, EngagementId, Owner, Fee, SentOn, Client, OrgHint, Project, Notes) VALUES",
        ',\n'.join(rows) + ';', "",
        "UPDATE m SET OrgId = o.Id FROM #m m JOIN opportunities.CanonicalOrg o ON o.Id = m.OrgHint AND o.RetiredAtUtc IS NULL;",
        "UPDATE m SET OrgId = x.Id FROM #m m CROSS APPLY (SELECT MIN(o.Id) AS Id, COUNT(*) AS N FROM opportunities.CanonicalOrg o",
        "    WHERE o.DisplayName = m.Client AND o.RetiredAtUtc IS NULL) x WHERE m.OrgId IS NULL AND x.N = 1;"]
# The sent date is taken as 5 pm Pacific (daylight time) that day.
sent = "TODATETIMEOFFSET(DATEADD(hour, 17, CAST(m.SentOn AS DATETIME2)), '-07:00')"
header = f"""/*
    Kor.OpportunitiesDb migration 373: open proposals into the CRM as Submitted (Ian approved the list 2026-10-20).

    Migration 368 imported DECIDED tracker pursuits only and left Open / Pending out, so the CRM had no Submitted pursuits and
    the roll-ups' follow-up (14 days) and chase (45 days) had nothing real to run on. This imports this year's open proposals
    from Desktop\\BD\\Management\\open-proposals-review-2026-10-20.csv, generated by tools/ManagementShare/open_proposals.py and
    turned into SQL by tools/ManagementShare/gen_open_import.py. {len(rows)} rows; {len(skipped)} left out for want of an owner.

      update  a live pursuit for the same client moves to Submitted; fee filled only if empty; prior stage and fee kept in
              opportunities.CrmOpenProposalImport.
      new     a Submitted pursuit: owner from the lead's initials, fee, project, client org (368 rule), ExternalSource
              'M.OpenProposals', key 'M:<record ids>'.
    Both write a CrmEngagementStageHistory row (Stage 3) at the date the fee was sent, 5 pm Pacific.

    Idempotent (NOT EXISTS on the import ledger and the external key). Reversible:
        UPDATE e SET Stage = i.PriorStage, ProposedFee = i.PriorFee FROM opportunities.CrmEngagements e
            JOIN opportunities.CrmOpenProposalImport i ON i.EngagementId = e.Id AND i.Action = N'update';
        DELETE h FROM opportunities.CrmEngagementStageHistory h JOIN opportunities.CrmOpenProposalImport i
            ON i.EngagementId = h.EngagementId AND h.ByStaffId = N'migration 373';
        DELETE FROM opportunities.CrmEngagements WHERE ExternalSource = N'M.OpenProposals';
*/"""
body = [
    "IF OBJECT_ID(N'opportunities.CrmOpenProposalImport', N'U') IS NULL",
    "    CREATE TABLE opportunities.CrmOpenProposalImport (SourceKey NVARCHAR(400) NOT NULL CONSTRAINT PK_CrmOpenProposalImport PRIMARY KEY,",
    "        EngagementId BIGINT NOT NULL, Action NVARCHAR(10) NOT NULL, PriorStage INT NULL, PriorFee DECIMAL(18,2) NULL,",
    "        ImportedAtUtc DATETIMEOFFSET NOT NULL CONSTRAINT DF_CrmOpenProposalImport_At DEFAULT sysdatetimeoffset());",
    "", "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "",
    "-- update: live pursuits only, once.",
    "INSERT INTO opportunities.CrmOpenProposalImport (SourceKey, EngagementId, Action, PriorStage, PriorFee)",
    "SELECT m.SourceKey, e.Id, N'update', e.Stage, e.ProposedFee FROM #m m JOIN opportunities.CrmEngagements e ON e.Id = m.EngagementId",
    "WHERE m.Action = N'update' AND e.Stage = 1 AND NOT EXISTS (SELECT 1 FROM opportunities.CrmOpenProposalImport i WHERE i.SourceKey = m.SourceKey);",
    "UPDATE e SET Stage = 3, ProposedFee = COALESCE(e.ProposedFee, m.Fee), UpdatedAtUtc = sysdatetimeoffset(), UpdatedBy = " + q(BY) + ",",
    "    Notes = CASE WHEN e.Notes IS NULL OR e.Notes = N'' THEN m.Notes ELSE e.Notes + N' | ' + m.Notes END",
    "FROM opportunities.CrmEngagements e JOIN #m m ON m.EngagementId = e.Id",
    "JOIN opportunities.CrmOpenProposalImport i ON i.SourceKey = m.SourceKey AND i.EngagementId = e.Id AND i.Action = N'update'",
    "WHERE e.Stage = 1;",
    "",
    "-- new: one Submitted pursuit per proposal.",
    "DECLARE @new TABLE (Id BIGINT NOT NULL, SourceKey NVARCHAR(400) NOT NULL);",
    "INSERT INTO opportunities.CrmEngagements (Stage, OwnerStaffId, ProposedFee, Notes, OpenedAtUtc, CreatedBy, UpdatedBy,",
    "    BuyerCanonicalOrgId, PotentialProjects, ExternalSource, ExternalSourceKey)",
    "OUTPUT inserted.Id, inserted.ExternalSourceKey INTO @new (Id, SourceKey)",
    f"SELECT 3, m.Owner, m.Fee, m.Notes, {sent}, {q(BY)}, {q(BY)}, m.OrgId, m.Project, N'M.OpenProposals', m.SourceKey",
    "FROM #m m WHERE m.Action = N'new' AND NOT EXISTS (SELECT 1 FROM opportunities.CrmEngagements e",
    "    WHERE e.ExternalSource = N'M.OpenProposals' AND e.ExternalSourceKey = m.SourceKey);",
    "INSERT INTO opportunities.CrmOpenProposalImport (SourceKey, EngagementId, Action) SELECT n.SourceKey, n.Id, N'new' FROM @new n;",
    "",
    "-- Stage history at the sent date, for every pursuit this run moved or created.",
    "INSERT INTO opportunities.CrmEngagementStageHistory (EngagementId, Stage, EnteredAtUtc, ByStaffId)",
    f"SELECT i.EngagementId, 3, {sent}, N'migration 373' FROM opportunities.CrmOpenProposalImport i JOIN #m m ON m.SourceKey = i.SourceKey",
    "WHERE NOT EXISTS (SELECT 1 FROM opportunities.CrmEngagementStageHistory h WHERE h.EngagementId = i.EngagementId AND h.ByStaffId = N'migration 373');",
    "", "COMMIT;", "",
    "SELECT i.Action, COUNT(*) AS Rows FROM opportunities.CrmOpenProposalImport i GROUP BY i.Action;",
    "SELECT COUNT(*) AS LiveSubmitted FROM opportunities.CrmEngagements WHERE Stage = 3;",
]
dry = [
    "SELECT 'rows in the approved list' AS Measure, COUNT(*) AS N FROM #m",
    "UNION ALL SELECT 'updates whose pursuit is live (stage 1)', COUNT(*) FROM #m m JOIN opportunities.CrmEngagements e ON e.Id = m.EngagementId WHERE m.Action = N'update' AND e.Stage = 1",
    "UNION ALL SELECT 'updates whose pursuit is NOT live (skipped)', COUNT(*) FROM #m m LEFT JOIN opportunities.CrmEngagements e ON e.Id = m.EngagementId WHERE m.Action = N'update' AND (e.Id IS NULL OR e.Stage <> 1)",
    "UNION ALL SELECT 'new pursuits', COUNT(*) FROM #m m WHERE m.Action = N'new' AND NOT EXISTS (SELECT 1 FROM opportunities.CrmEngagements e WHERE e.ExternalSource = N'M.OpenProposals' AND e.ExternalSourceKey = m.SourceKey)",
    "UNION ALL SELECT 'new pursuits with a resolved client org', COUNT(*) FROM #m m WHERE m.Action = N'new' AND m.OrgId IS NOT NULL",
    "UNION ALL SELECT 'owners not in BdStaff', COUNT(*) FROM #m m WHERE NOT EXISTS (SELECT 1 FROM opportunities.BdStaff s WHERE s.StaffKey = m.Owner COLLATE SQL_Latin1_General_CP1_CI_AS)",
    "UNION ALL SELECT 'Submitted pursuits in the CRM now', COUNT(*) FROM opportunities.CrmEngagements WHERE Stage = 3;",
]
open(out_sql, 'w', encoding='utf-8').write(header + '\n' + '\n'.join(load) + '\n\n' + '\n'.join(body) + '\n')
open(out_dry, 'w', encoding='utf-8').write('-- Dry run of migration 373: counts only, writes nothing.\n' + '\n'.join(load) + '\n\n' + '\n'.join(dry) + '\n')
updates = sum(1 for r in rows if "N'update'" in r)
print(f"{len(rows)} rows ({updates} update, {len(rows) - updates} new); left out for no owner: {', '.join(skipped)}")

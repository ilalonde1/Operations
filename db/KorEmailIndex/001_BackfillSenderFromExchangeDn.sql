INSERT INTO dbo.Backfill_20260930_FromEmailDn (EmailId, OldFromEmail, NewFromEmail)
SELECT e.EmailId, e.FromEmail, m.Smtp
FROM dbo.Emails e
JOIN @map m ON e.FromEmail = m.Dn
WHERE NOT EXISTS (SELECT 1 FROM dbo.Backfill_20260930_FromEmailDn b WHERE b.EmailId = e.EmailId);
